import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const APP_DIR = path.join(process.cwd(), "app"); // change to "app" if you have no src/
const OUT_DIR = path.join(process.cwd(), "src/generated");
const PAGE_FILES = new Set(["page.tsx", "page.ts", "page.jsx", "page.js", "page.mdx"]);

function walk(dir: string, segments: string[], found: string[][]): void {
    for (const entry of readdirSync(dir)) {
        const full = path.join(dir, entry);

        if (statSync(full).isDirectory()) {
            // skip parallel slots (@x), private folders (_x), intercepting routes ((.)x)
            if (entry.startsWith("@") || entry.startsWith("_") || /^\(\.{1,3}\)/.test(entry)) continue;

            const isGroup = /^\(.+\)$/.test(entry); // (marketing) is not part of the URL
            walk(full, isGroup ? segments : [...segments, entry], found);
        } else if (PAGE_FILES.has(entry)) {
            found.push(segments);
        }
    }
}

const toWord = (s: string): string => s.replace(/[^a-zA-Z0-9]+/g, "_").toUpperCase();

interface Param {
    name: string;
    catchAll: boolean;
}

function buildEntry(segments: string[]) {
    const params: Param[] = [];
    const keyParts: string[] = [];
    const urlParts: string[] = [];

    for (const seg of segments) {
        const dyn = seg.match(/^\[{1,2}(\.\.\.)?(\w+)\]{1,2}$/);
        if (dyn) {
            const name = dyn[2];
            const catchAll = Boolean(dyn[1]);
            params.push({ name, catchAll });
            keyParts.push(toWord(name));
            urlParts.push(catchAll ? `\${${name}.join("/")}` : `\${${name}}`);
        } else {
            keyParts.push(toWord(seg));
            urlParts.push(seg);
        }
    }

    const key = keyParts.length ? keyParts.join("_") : "HOME";
    const url = "/" + urlParts.join("/");
    return { key, url, params };
}

function main(): void {
    const found: string[][] = [];
    walk(APP_DIR, [], found);

    const entries = found.map(buildEntry).sort((a, b) => a.key.localeCompare(b.key));

    // detect duplicate keys
    const seen = new Set<string>();
    for (const e of entries) {
        if (seen.has(e.key)) throw new Error(`Duplicate route key "${e.key}" (${e.url})`);
        seen.add(e.key);
    }

    const lines = entries.map(({ key, url, params }) => {
        if (params.length === 0) return `  ${key}: "${url}",`;
        const args = params
            .map((p) => `${p.name}: ${p.catchAll ? "string[]" : "string"}`)
            .join(", ");
        return `  ${key}: (${args}) => \`${url}\`,`;
    });

    const ts = `// AUTO-GENERATED by scripts/generate-routes.ts. DO NOT EDIT.
export const ROUTES = {
${lines.join("\n")}
} as const;

export type RouteKey = keyof typeof ROUTES;
`;

    const json = JSON.stringify(
        entries.map(({ key, url }) => ({ key, path: url.replace(/\$\{(\w+)(\.join\("\/"\))?\}/g, "[$1]") })),
        null,
        2
    );

    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(path.join(OUT_DIR, "routes.ts"), ts);
    writeFileSync(path.join(OUT_DIR, "routes.json"), json + "\n");
    console.log(`Generated ${entries.length} routes`);
}

main();